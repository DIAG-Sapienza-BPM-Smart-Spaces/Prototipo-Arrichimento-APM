import json
import numpy as np
from thefuzz import process
from langchain_ollama import OllamaEmbeddings
import config

# Fields to be validated from the closed list
CLOSED_LIST_FIELDS = {"kw_tipo_intervento", "kw_sintomo", "kw_sistema", "kw_esito"}

# Free extraction fields — NO taxonomy validation, only format cleaning
FREE_FIELDS = {"kw_componente", "kw_luogo", "kw_azione"}

# Ollama Embedding Model
embedder = OllamaEmbeddings(
    model=config.OLLAMA_EMBEDDING_MODEL, 
    base_url=config.OLLAMA_BASE_URL
)

# Vector Memory (Caching taxonomy vectors to speed up the system)
_taxonomy_vectors_cache = {}

def cosine_similarity(vec1, vec2):
    """Calculates the semantic similarity (between 0 and 1) between two vectors."""
    v1, v2 = np.array(vec1), np.array(vec2)
    if np.linalg.norm(v1) == 0 or np.linalg.norm(v2) == 0:
        return 0.0
    return np.dot(v1, v2) / (np.linalg.norm(v1) * np.linalg.norm(v2))

def get_taxonomy_vectors(taxonomy: dict) -> dict:
    """Vectorizes the definitions (descriptions) and values in the taxonomy."""
    global _taxonomy_vectors_cache
    if _taxonomy_vectors_cache:
        return _taxonomy_vectors_cache

    print("  [System] Taxonomy vectors (Embeddings) are being created. Please wait...")
    vectors = {}
    
    for category, data in taxonomy.items():
        if category == "_meta" or f"kw_{category}" not in CLOSED_LIST_FIELDS:
            continue
            
        vectors[f"kw_{category}"] = {}
        
        if "values" in data:
            for val in data["values"]:
                if val in ("ALTRO", "N/A", "NON_SPECIFICATO"):
                    continue
                
                # Vectorize not just its name, but also its enriched description!
                desc = data.get("descriptions", {}).get(val, val)
                text_to_embed = f"{val}: {desc}"
                
                vec = embedder.embed_query(text_to_embed)
                vectors[f"kw_{category}"][val] = vec
                
    _taxonomy_vectors_cache = vectors
    return vectors

def semantic_match(query: str, category_vectors: dict, threshold: float = None) -> str:
    """Maps the text generated by the LLM to the value with the closest meaning in the taxonomy."""
    if threshold is None:
        threshold = getattr(config, "EMBED_THRESHOLD", 0.55)
    query_vec = embedder.embed_query(query)
    
    best_match = None
    best_score = -1.0
    
    for tax_val, tax_vec in category_vectors.items():
        score = cosine_similarity(query_vec, tax_vec)
        if score > best_score:
            best_score = score
            best_match = tax_val
            
    if best_score >= threshold:
        return best_match
    return "ALTRO"

def validate_against_taxonomy(result: dict, taxonomy: dict) -> dict:
    """
    Validates the LLM output using Embedding (Semantic Similarity) instead of thefuzz.
    """
    taxonomy_vectors = get_taxonomy_vectors(taxonomy)
    corrections = 0
    validated = result.copy()

    for field, value in result.items():
        if field == "kw_confidence":
            continue

        if field in FREE_FIELDS:
            if isinstance(value, str):
                validated[field] = value.strip().upper()
            continue

        if field not in CLOSED_LIST_FIELDS or field not in taxonomy_vectors:
            continue

        category_vecs = taxonomy_vectors[field]
        parts = [p.strip() for p in str(value).split(",") if p.strip()]
        validated_parts = []

        for part in parts:
            if part in taxonomy.get(field.replace("kw_", ""), {}).get("values", []) or part in ("N/A", "ERROR", "ALTRO"):
                validated_parts.append(part)
                continue

            # SEMANTIC MATCHING (EMBEDDING MATCH) ACTIVATED!
            match = semantic_match(part, category_vecs)
            validated_parts.append(match)
            corrections += 1

        # Remove duplicates
        unique = list(dict.fromkeys(validated_parts))
        validated[field] = ", ".join(unique) if unique else "N/A"

    validated["_corrections"] = corrections
    return validated

def validate_material(material_text: str, material_map: dict, threshold: int = 85) -> dict:
    """Fuzzy match the material definition in Excel with material_map.json."""
    if not material_text or material_text.strip() == "" or material_text.strip().lower() == "nan":
        return None
    best_match = process.extractOne(material_text.upper(), material_map.keys())
    if best_match and best_match[1] >= threshold:
        return material_map[best_match[0]]
    return None

def calculate_confidence(result: dict, taxonomy: dict, material_hint: dict) -> str:
    """
    Confidence score calculation — measures how 'uncertain/forced' the system is.
    High score = system is confident. Low score = human should review.

    NOTE: This score does not say 'strictly right/wrong'; it highlights the rows
    where the system struggled so that human-in-the-loop can intervene.
    """
    score = 100

    # 1. How many times embedding forced a correction (LLM produced a value outside the taxonomy)
    corrections = result.get("_corrections", 0)
    score -= corrections * 15

    # 2. Fields with ERROR (processing error) — severe
    error_count = sum(1 for k, v in result.items() if k.startswith("kw_") and v == "ERROR")
    score -= error_count * 30

    # 3. ALTRO in closed-list fields (could not classify) — uncertainty
    altro_count = sum(1 for k, v in result.items() if k in CLOSED_LIST_FIELDS and v == "ALTRO")
    score -= altro_count * 15

    # 4. (removed) material_map sistema cross-check — hard-coded, and its sistema
    #    names don't match the induced taxonomy, so it misfired. Material is now an
    #    LLM input, not an authority.

    # 5. Are CRITICAL fields empty/N/A — the system could not infer (strong uncertainty signal)
    def _empty(v):
        s = str(v).strip().upper()
        return s in ("", "N/A", "NAN", "NONE")

    # If sintomo or sistema is empty: it means the row is not fully resolved
    for field in ("kw_sintomo", "kw_sistema"):
        if _empty(result.get(field, "")):
            score -= 25

    # If primary azione is empty/ALTRO (even code + safety net couldn't find it): uncertain
    az = str(result.get("kw_azione", "")).strip().upper()
    if az in ("", "ALTRO", "N/A", "NAN"):
        score -= 20

    # 6. If too many fields are ALTRO/empty at the same time: cumulative uncertainty
    weak = sum(
        1 for f in ("kw_sintomo", "kw_sistema", "kw_azione", "kw_componente")
        if str(result.get(f, "")).strip().upper() in ("", "ALTRO", "N/A", "NAN")
    )
    if weak >= 2:
        score -= 15  # extra penalty if more than one critical field is weak

    # Thresholds: HIGH passes confidently, MEDIUM/LOW goes to review
    if score >= 85:
        return "HIGH"
    elif score >= 55:
        return "MEDIUM"
    else:
        return "LOW"
